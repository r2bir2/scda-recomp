"""Generate src/gpu/shim/epoxy/gl_funcs.h, the X-macro list of every OpenGL
entry point the imported xemu renderer (and our own glue) calls.

The renderer was written against libepoxy, which resolves GL functions
lazily. Here they are resolved once, after the WGL context exists, by
src/gpu/gl_loader.c; this list is what it walks. Rerun after adding files:

    py -3 src/gpu/gen_gl_loader.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = list((ROOT / "xemu" / "hw").rglob("*.[ch]")) + [
    p for p in ROOT.glob("*.c")]
HEADERS = [ROOT / "shim" / "GL" / "glcorearb.h",
           ROOT / "shim" / "GL" / "glext_memory_object.h"]
OUT = ROOT / "shim" / "epoxy" / "gl_funcs.h"

call = re.compile(r"\b(gl[A-Z][A-Za-z0-9]*)\s*\(")
used = set()
for src in SOURCES:
    used.update(call.findall(src.read_text(encoding="utf-8", errors="replace")))

declared = set()
for header in HEADERS:
    declared.update(re.findall(r"GLAPI [^;]*?\bAPIENTRY (gl[A-Za-z0-9]+)\s*\(",
                               header.read_text(encoding="utf-8")))
names = sorted(n for n in used if n in declared)
missing = sorted(n for n in used if n not in declared)

lines = [
    "/* Generated by src/gpu/gen_gl_loader.py -- do not edit. */",
    "/* GLFN(pfn_type, name) for each GL entry point the renderer uses. */",
]
lines += [f"GLFN(PFN{n.upper()}PROC, {n})" for n in names]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
remap = ["/* Generated by src/gpu/gen_gl_loader.py -- do not edit. */"]
remap += [f"#define {n} xgl_{n}" for n in names]
(OUT.parent / "gl_remap.h").write_text("\n".join(remap) + "\n", encoding="utf-8")
print(f"{len(names)} GL functions -> {OUT}")
if missing:
    print("not GL core entry points (macros/helpers, check by hand):",
          ", ".join(missing))
