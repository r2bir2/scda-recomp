"""List the Direct3D 8 entry points the HLE renderer replaces, with addresses.

Sources (MIT, (c) 2026 TGP482, Joshhhuaaa -- SCDA-XBERecomp):
  src/xdk/d3d8.cpp      the HLE_* function set (names, convention, stack args)
  config/scda_v2.toml   [symbols] name = address for this XBE
  config/xdk_symbols.toml address = "D3D8::name"
Verified 2026-10-26 against our function database: every D3D8 function
address is an exact function start (docs: agent_handoff/HLE_RENDERER_PLAN.md).

Usage: py -3 tools/hle/d3d_symbols.py <TGP repo> > projects/scda/hle_d3d_functions.json
"""
import json
import re
import sys


def main():
    repo = sys.argv[1] if len(sys.argv) > 1 else "C:/VScode/SCDA-XBERecomp_TGP482"
    src = open(f"{repo}/src/xdk/d3d8.cpp", encoding="utf-8").read()
    syms = {}
    for path in (f"{repo}/config/scda_v2.toml", f"{repo}/config/xdk_symbols.toml"):
        txt = open(path, encoding="utf-8").read()
        for name, addr in re.findall(r"^(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", txt, re.M):
            syms.setdefault(name, int(addr, 16))
        for addr, name in re.findall(r'^(0x[0-9A-Fa-f]+)\s*=\s*"(?:\w+::)?(\w+)"', txt, re.M):
            syms.setdefault(name, int(addr, 16))

    funcs = []
    for conv, name, nargs in re.findall(r"HLE_(STDCALL|FASTCALL|CDECL)\((\w+)\s*,?\s*(\d*)\)", src):
        if "##" in name:
            continue
        funcs.append((name, conv.lower(), int(nargs or 0)))
    # plain X86_FUNC(GUEST(name)) overrides around the original: (name, convention, stack args)
    for name, conv, nargs in (("Lock2DSurface", "stdcall", 6),):
        if re.search(r"X86_FUNC\(GUEST\(" + name + r"\)\)", src):
            funcs.append((name, conv, nargs))
    # COMPLEX_STATE(name, rs) expands to HLE_STDCALL(D3DDevice_SetRenderState_##name, 1)
    for name in re.findall(r"^COMPLEX_STATE\((\w+),", src, re.M):
        funcs.append((f"D3DDevice_SetRenderState_{name}", "stdcall", 1))

    out, missing = [], []
    for name, conv, nargs in funcs:
        addr = syms.get(name, 0)
        if not addr:
            missing.append(name)
            continue
        out.append({"name": name, "address": f"0x{addr:08X}", "convention": conv, "stack_args": nargs})
    globals_ = {n: f"0x{a:08X}" for n, a in syms.items()
                if n.startswith("D3D_") and a >= 0x4A0000 and n in
                ("D3D_Device", "D3D_pDevice", "D3D_IndexData", "D3D_DirtyFlags",
                 "D3D_DeferredTextureState", "D3D_RenderState", "D3D_Streams",
                 "D3D_SimpleRenderStateEncode")}
    json.dump({"functions": out, "absent_in_image": missing, "globals": globals_}, sys.stdout, indent=1)
    # SYM_<name> for the SCDA-XBERecomp sources (their hle.h: SYM(name) = 0x##SYM_name)
    import os
    hdr = os.path.join(os.path.dirname(__file__), "..", "..", "projects", "scda", "src", "hle",
                       "compat", "image_symbols.h")
    lines = ["// Generated by tools/hle/d3d_symbols.py from SCDA-XBERecomp's config/scda_v2.toml and",
             "// config/xdk_symbols.toml (MIT, (c) 2026 TGP482, Joshhhuaaa) -- do not edit.",
             "#pragma once"]
    for name in sorted(syms):
        if syms[name]:
            lines.append(f"#define SYM_{name} {syms[name]:X}")
    open(hdr, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(out)} functions, {len(missing)} absent in this image", file=sys.stderr)


if __name__ == "__main__":
    main()
