"""Generate the HLE renderer's sub_X_gen wrappers from hle_d3d_functions.json.

Writes:
  projects/scda/src/hle_d3d_wrappers.c  void sub_X(void) for every D3D entry
      point: hle_d3d_call(id) decides whether the HLE renderer handled it,
      otherwise the recompiled original runs as sub_X_gen(). The generator
      (tools/recomp --exclude-manual <this file>) renames the bodies.
  projects/scda/src/hle_d3d_ids.h  the ids, names, addresses, conventions.

Functions that already have a hand-written wrapper elsewhere are skipped and
listed in SKIP (they call into the HLE renderer from there).

Usage: py -3 tools/hle/gen_d3d_wrappers.py
Docs: agent_handoff/HLE_RENDERER_PLAN.md (milestone M1).
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SRC = os.path.join(ROOT, "projects", "scda", "hle_d3d_functions.json")
OUT_C = os.path.join(ROOT, "projects", "scda", "src", "hle_d3d_wrappers.c")
OUT_H = os.path.join(ROOT, "projects", "scda", "src", "hle_d3d_ids.h")

# already wrapped in recomp_manual.c (60 FPS policy around the swap)
SKIP = {"D3DDevice_Swap"}


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    funcs = [f for f in data["functions"] if f["name"] not in SKIP]
    funcs.sort(key=lambda f: int(f["address"], 16))

    h = ["/* Generated by tools/hle/gen_d3d_wrappers.py from projects/scda/hle_d3d_functions.json",
         " * -- do not edit. Direct3D 8 (XDK 5849) entry points of the SCDA XBE; names and",
         " * addresses from SCDA-XBERecomp (MIT, (c) 2026 TGP482, Joshhhuaaa). */",
         "#pragma once",
         "#include <stdint.h>",
         "",
         "enum hle_d3d_conv { HLE_STDCALL, HLE_FASTCALL, HLE_CDECL };",
         "",
         "enum hle_d3d_id {"]
    for f in funcs:
        h.append(f"    HLE_D3D_{f['name']},")
    h += ["    HLE_D3D__COUNT", "};", "",
          "typedef struct { const char *name; uint32_t address; uint8_t conv, stack_args; } hle_d3d_info;",
          "extern const hle_d3d_info g_hle_d3d_info[HLE_D3D__COUNT];", "",
          "/* globals of the XDK's D3D in this image */"]
    for name, addr in sorted(data["globals"].items()):
        h.append(f"#define HLE_{name.upper()} {addr}u")
    h.append("")

    c = ["/* Generated by tools/hle/gen_d3d_wrappers.py -- do not edit.",
         " *",
         " * HLE renderer entry points (agent_handoff/HLE_RENDERER_PLAN.md): every Direct3D 8",
         " * function the HLE renderer can replace. hle_d3d_call() returns nonzero when the",
         " * HLE renderer handled the call (it then also did the stack cleanup and set eax);",
         " * otherwise the recompiled original runs. The recompiler renames the originals to",
         " * sub_X_gen because this file declares them so (--exclude-manual). */",
         '#include "recomp_types.h"',
         '#include "hle_d3d_ids.h"',
         "",
         "int hle_d3d_call(enum hle_d3d_id id);",
         "",
         "const hle_d3d_info g_hle_d3d_info[HLE_D3D__COUNT] = {"]
    for f in funcs:
        conv = {"stdcall": "HLE_STDCALL", "fastcall": "HLE_FASTCALL", "cdecl": "HLE_CDECL"}[f["convention"]]
        c.append(f'    {{ "{f["name"]}", {f["address"]}u, {conv}, {f["stack_args"]} }},')
    c += ["};", ""]
    for f in funcs:
        a = int(f["address"], 16)
        c += [f"/* {f['name']} ({f['convention']}, {f['stack_args']} stack args) */",
              f"extern void sub_{a:08X}_gen(void);",
              f"void sub_{a:08X}(void)",
              "{",
              f"    if (hle_d3d_call(HLE_D3D_{f['name']}))",
              "        return;",
              f"    sub_{a:08X}_gen();",
              "}",
              ""]
    open(OUT_H, "w", encoding="utf-8", newline="\n").write("\n".join(h))
    open(OUT_C, "w", encoding="utf-8", newline="\n").write("\n".join(c))
    print(f"{len(funcs)} wrappers -> {OUT_C}")


if __name__ == "__main__":
    main()
